'use strict';
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, '../bikes-frames.html'), 'utf8');
const script = html.match(/<script>\s*(const products=[\s\S]*?)<\/script>/)[1];
const nodes = {};
const document = { getElementById(id) {
  return nodes[id] || (nodes[id] = { value: '', textContent: '', innerHTML: '', style: {}, addEventListener() {} });
} };
const window = { location: { search: '', pathname: '/bikes-frames.html' }, addEventListener() {} };
for (const name of ['Supplier', 'Fcc', 'Cadence', 'Tfsa']) window['cyclifyMerge' + name + 'Products'] = () => {};
const context = { document, window, localStorage: { getItem: () => null }, history: { pushState() {} }, URLSearchParams, console };
vm.createContext(context);
vm.runInContext(script, context);
assert(nodes.products.innerHTML.includes('TAVELO Arow'));
vm.runInContext('selectCategory("tavelo")', context);
assert.equal(window.location, 'tavelo-arow.html');
window.location = { search: '?category=tavelo', pathname: '/bikes-frames.html' };
vm.runInContext('activeCategory="tavelo";renderProducts()', context);
assert.equal(nodes.categorySummary.textContent, 'TAVELO | 1 products');
assert(!nodes.products.innerHTML.includes('SAVA'));
assert(nodes.products.innerHTML.includes('Configure Bike'));
assert(!nodes.products.innerHTML.includes('MRP'));
vm.runInContext('openProduct(990001)', context);
assert.equal(window.location, 'tavelo-arow.html');
assert(html.indexOf('key:"sava"') < html.indexOf('key:"tavelo"'));
assert(!html.includes('TAVELO Arow · Build your road bike'));
console.log('Passed: Tavelo brand-icon navigation, grid card, no MRP and no separate banner.');
