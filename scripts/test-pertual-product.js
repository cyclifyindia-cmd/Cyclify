const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const cheerio = require('cheerio');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const source = read('product.html');
const products = vm.runInNewContext('(' + source.match(/const products=(\[[\s\S]*?\]);/)[1] + ')');
const product = products.find(item => item.id === 88003);
assert.equal(product.price, 99999);
assert.equal(product.mrp, 103000);
assert.equal(product.available, true);
assert.deepEqual(Array.from(product.sizes), ['Shimano HG', 'SRAM XDR']);
assert.equal(product.images.length, 6);
for (const image of product.images) assert(fs.statSync(path.join(root, image)).size > 10000);
const page = 'products/tavelo-pertual-sharp-gr-47-53-carbon-gravel-wheelset-88003.html';
const $ = cheerio.load(read(page));
assert.equal($('#sizeSection .size-label').text(), 'Select Freehub');
assert($('link[rel="canonical"]').attr('href').endsWith(page));
assert($('#productPrice').text().includes('99,999'));
const feed = cheerio.load(read('google-merchant-feed.xml'), { xmlMode: true });
const item = feed('item').filter((_, element) => feed(element).find('g\\:id').text() === 'CYCLIFY-88003');
assert.equal(item.length, 1);
assert.equal(item.children('g\\:price').text(), '103000.00 INR');
assert.equal(item.find('g\\:sale_price').text(), '99999.00 INR');
assert.equal(item.find('g\\:availability').text(), 'in_stock');
assert(read('wheels-tyres.html').includes('href="' + page + '"'));
assert(read('sitemap.xml').includes(page));
const catalog = JSON.parse(read('marketplace-backend/payment-function/functions/catalog.json')).products['88003'];
assert.equal(catalog.price, 99999);
assert.equal(catalog.requiredOption, true);
assert.deepEqual(catalog.sizes, ['Shimano HG', 'SRAM XDR']);
const { validatedCart } = require('../marketplace-backend/payment-function/functions/index')._test;
for (const size of catalog.sizes) {
  const order = validatedCart([{ id: '88003', size, quantity: 1, price: 1 }]);
  assert.equal(order.total, 99999, 'Checkout must ignore client-side prices');
  assert.equal(order.items[0].size, size);
}
assert.throws(() => validatedCart([{ id: '88003', quantity: 1 }]), /Choose an option/);
assert.throws(() => validatedCart([{ id: '88003', size: 'Unknown', quantity: 1 }]), /invalid/);
console.log('PERTUAL verified: photos, freehub choices, prices, category, SEO, feed and server-side checkout.');
